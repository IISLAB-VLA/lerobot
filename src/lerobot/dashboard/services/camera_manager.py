"""Camera manager Protocol, in-memory fallback, and lerobot-backed implementation.

The dashboard depends on a single :class:`CameraManagerProtocol` so the HTTP
routes, WebRTC streaming tracks, dataset recorder, and VLA inference can share
one capture loop per camera. Two concrete managers ship here:

* :class:`InMemoryCameraManager` — no-hardware fallback used when the server
  runs with ``fake_devices=True`` or inside unit tests. It fabricates all-zero
  frames at the entry's declared fps.
* :class:`LerobotCameraManager` — wraps :class:`lerobot.cameras.Camera`
  backends (OpenCV / RealSense) behind an async pub/sub hub. One capture task
  per camera pulls frames via :func:`asyncio.to_thread`; every subscriber gets
  a dedicated :class:`asyncio.Queue` with ``maxsize=1`` so the latest frame is
  always immediately available and slow consumers cannot stall the producer.

Streaming consumers (``src/lerobot/dashboard/streaming/``) call
:meth:`CameraManagerProtocol.subscribe` to pull frames; the signature
intentionally mirrors :class:`lerobot.dashboard.streaming.source.FrameSource`
so a thin adapter is all that's needed to bridge the two.

The subscribe-time contract was confirmed with streaming-engineer-3 on
2026-04-14: shared read-only ``ndarray`` (no per-subscriber copy) and no frame
envelope — WebRTC PTS is generated by :class:`LeRobotCameraTrack`.
"""

from __future__ import annotations

import asyncio
import logging
from collections.abc import AsyncIterator, Callable
from dataclasses import dataclass, field
from datetime import UTC, datetime
from typing import TYPE_CHECKING, Any, Protocol, runtime_checkable
from uuid import UUID

import numpy as np

from lerobot.dashboard.services.registry_models import CameraEntry, CameraStatus
from lerobot.dashboard.streaming.source import FrameSourceError

if TYPE_CHECKING:  # pragma: no cover — avoid heavy imports at module load
    from lerobot.cameras import Camera

logger = logging.getLogger(__name__)

# Sentinel broadcast through a subscriber queue to signal graceful close.
_CLOSE_SENTINEL = object()


@runtime_checkable
class CameraManagerProtocol(Protocol):
    """Live runtime for dashboard-declared cameras."""

    async def open(self, entry: CameraEntry) -> CameraStatus:
        """Acquire hardware handles for ``entry`` and mark it open."""

    async def close(self, camera_id: UUID) -> CameraStatus:
        """Release hardware handles for ``camera_id``."""

    async def is_open(self, camera_id: UUID) -> bool:
        """Return ``True`` if the camera is currently capturing."""

    async def get_status(self, camera_id: UUID) -> CameraStatus:
        """Return the most recent runtime status for ``camera_id``."""

    def subscribe(self, camera_id: UUID) -> AsyncIterator[np.ndarray]:
        """Yield HxWx3 ``uint8`` BGR frames until the subscriber is cancelled.

        Each subscriber gets an independent iterator; dropping the iterator
        (GC or explicit ``aclose``) decrements :attr:`CameraStatus.subscriber_count`.
        """


# ---------------------------------------------------------------------------
# InMemoryCameraManager — fake_devices / unit-test fallback
# ---------------------------------------------------------------------------


@dataclass(slots=True)
class _InMemorySlot:
    status: CameraStatus = field(default_factory=CameraStatus)
    entry: CameraEntry | None = None
    subscribers: int = 0


class InMemoryCameraManager:
    """Fallback :class:`CameraManagerProtocol` that never touches hardware.

    :meth:`subscribe` yields zero-filled frames at the camera's declared fps
    — enough to drive WebRTC negotiation in tests and ``fake_devices`` mode
    without pulling in OpenCV or librealsense.
    """

    def __init__(self) -> None:
        self._lock = asyncio.Lock()
        self._slots: dict[UUID, _InMemorySlot] = {}

    async def open(self, entry: CameraEntry) -> CameraStatus:
        async with self._lock:
            slot = self._slots.setdefault(entry.id, _InMemorySlot())
            slot.entry = entry
            slot.status = CameraStatus(
                online=True,
                last_error=None,
                opened_at=datetime.now(UTC),
                subscriber_count=slot.subscribers,
            )
            return slot.status.model_copy()

    async def close(self, camera_id: UUID) -> CameraStatus:
        async with self._lock:
            slot = self._slots.get(camera_id)
            if slot is None:
                return CameraStatus()
            slot.status = CameraStatus(
                online=False,
                last_error=slot.status.last_error,
                opened_at=slot.status.opened_at,
                subscriber_count=slot.subscribers,
            )
            return slot.status.model_copy()

    async def is_open(self, camera_id: UUID) -> bool:
        async with self._lock:
            slot = self._slots.get(camera_id)
            return bool(slot and slot.status.online)

    async def get_status(self, camera_id: UUID) -> CameraStatus:
        async with self._lock:
            slot = self._slots.get(camera_id)
            if slot is None:
                return CameraStatus()
            return slot.status.model_copy(update={"subscriber_count": slot.subscribers})

    async def _increment(self, camera_id: UUID) -> None:
        async with self._lock:
            slot = self._slots.get(camera_id)
            if slot is not None:
                slot.subscribers += 1

    async def _decrement(self, camera_id: UUID) -> None:
        async with self._lock:
            slot = self._slots.get(camera_id)
            if slot is not None:
                slot.subscribers = max(0, slot.subscribers - 1)

    async def subscribe(self, camera_id: UUID) -> AsyncIterator[np.ndarray]:
        slot = self._slots.get(camera_id)
        if slot is None or slot.entry is None or not slot.status.online:
            return
        entry = slot.entry
        fps = max(int(entry.fps), 1)
        await self._increment(camera_id)
        try:
            while True:
                slot = self._slots.get(camera_id)
                if slot is None or not slot.status.online:
                    return
                yield np.zeros((entry.height, entry.width, 3), dtype=np.uint8)
                await asyncio.sleep(1.0 / fps)
        finally:
            await self._decrement(camera_id)


