def _enqueue_drop_oldest(queue: asyncio.Queue[Any], item: Any) -> None:
    """Put ``item`` on the bounded queue, discarding the oldest on overflow."""
    if queue.full():
        try:
            queue.get_nowait()
        except asyncio.QueueEmpty:
            pass
    try:
        queue.put_nowait(item)
    except asyncio.QueueFull:  # pragma: no cover — race with another producer
        pass


def _safe_async_read(camera: Camera) -> np.ndarray | None:
    """Wrapper that calls ``camera.async_read`` with the SDK's default timeout.

    :class:`lerobot.cameras.Camera` defines ``async_read(timeout_ms=...)`` so
    we let each backend choose its own default. Some backends return ``None``
    when no new frame has arrived — the capture loop treats that as a benign
    retry.
    """
    return camera.async_read()


